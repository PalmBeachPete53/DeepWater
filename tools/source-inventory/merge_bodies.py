#!/usr/bin/env python3
"""Merges what each catalogue body holds (first pass holds_*.jsonl, verification gapfix_*.jsonl) with the probe and the
cards into docs/sources/catalog/bodies.jsonl and docs/sources/catalogue-bodies.md, and prints coverage.

A frequency stays only where the body's own pages were read: the first pass often inferred it from the indicator.

    merge_bodies.py   (from the repository's root)
"""
import collections
import glob
import gzip
import json
import re

DATA = "resources/data_sources.json"
CAT = "docs/sources/catalog/"


def jsonl(path):
    with (gzip.open if path.endswith(".gz") else open)(path, "rt", encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def cards():
    """catalogue name -> card id, and the rows each card claims, from the frontmatter."""
    names, rows = {}, {}
    for path in glob.glob("docs/sources/*.md"):
        text = open(path, encoding="utf-8").read()
        m = re.match(r"---\n(.*?)\n---", text, re.S)
        if not m:
            continue
        cid = None
        for line in m.group(1).splitlines():
            if line.startswith("id:"):
                cid = line.split(":", 1)[1].split("#")[0].strip()
        if not cid:
            continue
        for line in m.group(1).splitlines():
            if line.startswith("catalogue:"):
                try:
                    for n in json.loads(line.split(":", 1)[1].split(" #")[0].strip()):
                        names.setdefault(n, cid)
                except ValueError:
                    pass
            if line.startswith("rows:"):
                rows[cid] = re.findall(r"[a-z0-9_]+", line.split(":", 1)[1].split("#")[0])
    return names, rows


def clean(text):
    text = re.sub(r"\s*\((credited|credited only|crawl)\)", "", text)
    return re.sub(r"(?i)^per trading economics crawl:\s*", "", text).strip()


def main():
    data = json.load(open(DATA, encoding="utf-8"))
    entries = {}
    for path in sorted(glob.glob(CAT + "holds_*.jsonl")):
        for r in jsonl(path):
            entries[r["name"]] = r
    verified = 0
    for path in sorted(glob.glob(CAT + "gapfix_*.jsonl")):
        for r in jsonl(path):
            entries[r["name"]] = r
            verified += 1
    probe = {r["name"]: r for r in jsonl(CAT + "bodies_probe.jsonl.gz")}
    names, rows = cards()
    out = []
    for b in data["sources"]:
        # A merged body keeps the entry of whichever of its names was read best.
        rank = {"site": 3, "both": 3, "credited": 1, "none": 0}
        names_of = [b["name"]] + b.get("aliases", [])
        found = [entries[n] for n in names_of if n in entries]
        e = max(found, key=lambda x: rank.get(x.get("evidence"), 0)) if found else {
            "holds": "", "frequency": "", "machine": "unknown", "site": "", "evidence": "none", "note": ""}
        freq = e.get("frequency", "") if e.get("evidence") in ("site", "both") else ""
        if "general knowledge" in e.get("note", "").lower():
            freq = ""
        out.append({"name": b["name"], "kind": b["kind"], "countries": b["countries"], "access": b["access"],
                    "holds": clean(e.get("holds", "")), "frequency": freq, "machine": e.get("machine", "unknown"),
                    "site": b.get("url", ""), "evidence": e.get("evidence", "none"), "note": e.get("note", ""),
                    "aliases": b.get("aliases", []),
                    "probe_state": probe.get(e.get("name", b["name"]), {}).get("state", ""),
                    "card": next((names[n] for n in names_of if n in names), ""),
                    "calls": e.get("calls", [])})
    with open(CAT + "bodies.jsonl", "w", encoding="utf-8") as f:
        for r in out:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    def esc(s):
        return s.replace("|", "\\|").replace("\n", " ")

    by_country = collections.defaultdict(list)
    for r in out:
        by_country[r["countries"][0] if len(r["countries"]) == 1 else "Several countries"].append(r)
    with open("docs/sources/catalogue-bodies.md", "w", encoding="utf-8") as f:
        f.write("# The catalogue's bodies, by country\n\nWhat each of the %d bodies of `resources/data_sources.json` publishes, "
                "and how a program can read it. Generated by `tools/source-inventory/merge_bodies.py`; the same records "
                "with the calls behind them are in `catalog/bodies.jsonl`.\n\n"
                "**Evidence**: `site`/`both` = its own pages were read on 5 Nov 2026. `credited` = its site could not be read "
                "(refused, dead, script-only, none found): the subjects are those other publications credit to it, not "
                "checked at the source. **Frequency** appears only where its own pages were read, and is partly a reading "
                "of their labels.\n\n" % len(out))
        for c in sorted(by_country, key=lambda k: (k == "Several countries", k)):
            f.write(f"## {c}\n\n| Body | Holds | Freq. | Machine | Site | Evidence | Note |\n|---|---|---|---|---|---|---|\n")
            for r in sorted(by_country[c], key=lambda r: r["name"]):
                name = f"[{esc(r['name'])}]({r['card']}.md)" if r["card"] else esc(r["name"])
                if r["aliases"]:
                    name += " (also: " + esc("; ".join(r["aliases"])) + ")"
                f.write(f"| {name} | {esc(r['holds'])} | {esc(r['frequency'])} | {esc(r['machine'])} | {esc(r['site'])} | {r['evidence']} | {esc(r['note'])} |\n")
            f.write("\n")

    missing = [r["name"] for r in out if not r["holds"]]
    print("bodies", len(out), "empty holds", len(missing), "verified by gap pass", verified)
    print("evidence", collections.Counter(r["evidence"] for r in out))
    print("frequency kept", sum(1 for r in out if r["frequency"]))
    print("machine api", sum(1 for r in out if r["machine"].startswith("api")))
    print("linked to a card", sum(1 for r in out if r["card"]))
    src = open("src/SourcesPage.cpp", encoding="utf-8").read()
    all_rows = re.findall(r'\{"([a-z0-9_]+)",\s*Kind::\w+,', src)
    claimed = {x for v in rows.values() for x in v}
    print("rows", len(all_rows), "without a card", sorted(set(all_rows) - claimed))
    print("cards", len(rows))


if __name__ == "__main__":
    main()
